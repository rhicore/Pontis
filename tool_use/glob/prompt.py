"""Glob tool prompt — 图谱节点检索。"""

DESCRIPTION = "基于名称模式的快速检索工具，用于定位文件节点及其关联的实体节点。"

DETAIL = """\
path::entity 语法（支持多跳、双向遍历）：
- `*.db` — 查找所有 .db 文件节点（也匹配实体名含 .db 的节点）
- `**/*.db` — 查找含路径的 .db 文件（含 / 只匹配文件节点）
- `*.db::*.table` — 从 .db 文件节点遍历边，找到关联的 .table 实体
- `*.table::*.db` — 反向：从 .table 实体沿入边找到所属 .db 文件
- `*.db::*.table::*.*.*.col` — 多跳：文件 → 表 → 列
- `*user*.col` — 模糊匹配实体名（跨文件搜索）
- `*` — 列出所有节点

遍历规则：
- `::` 是边遍历操作符，双向（同时沿出边和入边）
- 含 `/` 的 pattern 段只匹配文件节点（实体名不含 `/`）
- 每跳自动去重

参数：
- path_pattern (必填): glob 模式，支持 :: 多跳
- offset: 起始位置（从 0 开始），默认 0
- limit: 每页最大条数，默认 100，最大 500

返回格式: 每行一个匹配，`[ref] | [简要信息]`。无匹配返回 "No objects found"。

结果截断时会提示总数和当前范围，使用 offset 参数翻页。

使用建议：
- 这是探索项目的第一步，先用 glob 了解结构
- glob 返回简要信息，需要详细信息时用 meta 工具
- 知道文件找实体用正向 :: ，知道实体找文件用反向 ::\
"""


def get_description() -> str:
    return f"{DESCRIPTION}\n\n{DETAIL}"
