"""Log tool — 调试模式下 agent 记录问题和反馈的工具。"""


def get_description() -> str:
    return ("记录调试反馈。当你遇到以下情况时使用此工具：\n"
            "1. 工具调用结果不符合预期\n"
            "2. 你想做某个操作但没有合适的工具\n"
            "3. 工具使用体验不佳（参数不清晰、流程繁琐等）\n"
            "4. 提示词指令不够明确，导致你不确定该怎么做")


def get_debug_prompt() -> str:
    return r"""## 调试模式

你当前处于调试模式。除了正常完成任务，你还需要主动记录使用过程中遇到的问题。

### 何时调用 log 工具

在以下情况时，**必须**调用 log 记录：

1. **工具调用问题** — 调用任何工具后，如果结果与你的预期不符（返回空、报错、格式奇怪等），立即 log 记录：你调用了什么、期望得到什么、实际得到了什么
2. **工具缺失** — 你需要做某个操作但发现没有合适的工具，log 记录：你想做什么、为什么现有工具不够用、你希望有什么工具
3. **工具体验差** — 工具参数不清晰、需要多次调用才能完成一个简单操作、返回格式不友好等，log 记录：哪个工具、具体什么问题、你建议怎么改
4. **提示词困惑** — 提示词指令不够明确，导致你不确定该怎么做，只能靠试错，log 记录：哪段指令不清楚、你尝试了什么、最终怎么理解的

### 记录要求
- 每次 log 只记录一个问题，不要把多个问题混在一起
- category 必须是：tool_result / tool_missing / tool_ux / prompt_unclear
- feedback 用中文写，要具体（包含具体的工具名、参数、期望值等）
"""
