def get_tool_prompt() -> str:
    return r"""## 工具使用

### 工具选择

- **glob**：发现实体和关系，适合回答“有哪些”“连着什么”
- **meta**：读取单个实体的 detail / brief / sample / topk
- **query**：只在需要真实数据验证时使用
- **search**：名称不确定时做模糊检索
- **cypher**：处理 glob 不方便表达的复杂图查询
- **bash / grep**：最后手段

### 使用纪律

- 先发现，再理解，再验证；不要跳过 `glob/meta` 直接猜测写 SQL 或写图谱
- 已有结果直接复用，不要只为“再确认一次”重复调用
- 不要把 `glob("*")` 当作起手式；优先从数据库文件、表、README、已知实体或一跳邻居开始定向探索
- 结果截断时优先翻页，不要随意换查询语义
- 用中文回答，基于事实，不补会
"""
