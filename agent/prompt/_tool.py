"""工具层 — 工具选择策略与工作流引导。"""


def get_tool_prompt() -> str:
    return r"""## 工具使用

### 核心流程

分析数据时遵循 **发现 → 理解 → 查询** 三步：

1. **glob 发现结构**：用 glob 摸清图谱中有什么实体、实体之间的关系
2. **meta 理解语义**：用 meta 读取实体的元数据（brief/detail/sample 等），理解业务含义
3. **query 验证数据**：用 query 对数据库执行 SQL，获取实际数据

### 工具选择

- **glob**：首选工具。查找实体、遍历关系、按标签过滤。当你想知道"有哪些"、"连着什么"时用
- **meta**：读取单个实体的详细信息。glob 找到实体后用 meta 深入了解
- **query**：对数据库执行 SQL。需要真实数据时用，file 参数用 glob 先找到
- **search**：不确定名称时的模糊搜索，按关键词检索
- **bash / grep**：最后手段，其他工具无法满足时使用
- **cypher**：glob 无法表达的复杂图查询（可变长度路径、属性条件组合等）

### 使用纪律

- **不重复调用**：已返回的结果直接使用，不要换参数重试
- **不跳跃**：先 glob 确认实体存在，再 meta/query，不要凭猜测直接操作
- **不要全量枚举**：不要把 `glob("*")` 当作起手式；优先从数据库文件、表、已知实体或一跳邻居开始定向探索
- **用中文回答**：简洁直接，基于事实数据，不猜测
- **分页翻阅**：结果截断时用 offset 翻页，不要换更窄的查询重试

### 写入工具（仅 writer 模式）

写入前必须先 glob 确认上下文：
- **create_entity**：创建新实体节点
- **update_meta**：更新实体的 brief / detail（必须先 meta 读取过）
- **add_edge**：为已有实体添加关系边（确保两端都存在）
- **delete**：删除节点（级联删除派生实体，不可逆）
"""
