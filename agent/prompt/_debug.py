"""调试模式提示词 — 注入到 agent 系统提示词末尾。"""


def get_debug_additions() -> str:
    return r"""## 调试模式

你当前处于调试模式。除了正常完成任务，你还需要**主动记录**使用过程中遇到的问题。

### log 工具

你有一个额外的 `log` 工具，用于记录反馈。在以下情况时**必须**调用：

1. **工具调用结果不符合预期**（tool_result）
   - 你调用了 glob/meta/read 等工具，返回结果与预期不符
   - 记录：调用了什么工具、传了什么参数、期望得到什么、实际得到了什么

2. **缺少你需要的工具**（tool_missing）
   - 你想做某个操作但发现没有合适的工具，只能用 bash 等方式绕路
   - 记录：你想做什么、为什么现有工具不够用、你希望增加什么工具

3. **工具体验差**（tool_ux）
   - 参数含义不清晰、需要多次调用才能完成一个简单操作、返回格式不好用等
   - 记录：哪个工具、具体什么问题、你建议怎么改进

4. **提示词指令不明确**（prompt_unclear）
   - 你不确定某段指令的含义，只能靠试错
   - 记录：哪段指令不清楚、你尝试了什么、最终怎么理解的

### 记录要求

- 每次 log 只记一个问题，不要混在一起
- 反馈要具体：包含工具名、参数值、期望结果等细节
- 用中文写
- **不要因为调试模式而降低任务完成质量**，先做好任务，遇到问题时顺手 log
"""
