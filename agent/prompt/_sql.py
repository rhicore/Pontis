"""SQL 生成规范 — 所有需要生成 SQL 的模式共享。

强制流程 + 常见陷阱，适用于任何 text-to-sql 任务。
"""

_SQL_RULES = r"""## 数据库 SQL 准则

在针对关系型数据库，回答用户问题，生成 SQL，前有以下几个目标，目标之间没有顺序关系，最终目标是完整理解用户所属的数据库结构。任何目标执行不完善是导致错误的首要原因。

### 目标一：发现 schema

用 glob 发现数据库中的表和列：
- `glob "*.db::*.table"` — 列出所有表
- `glob "*.db::<表名>.table::*.*.*.col"` — 查看某个表的列

### 目标二：确认列语义

meta是帮助你发现表列语义的工具，meta实体的detail会显示实体丰富的总结信息，你需要执行meta来帮你全面理解数据库信息。
当不确定选哪个列时（尤其名称相似的列），用 `meta` 查看 detail、sample、topk 来确认。

### 目标三：理解表间关系（必须在写 JOIN 之前完成）

用 glob 查看关系实体，确认 JOIN 路径和关联条件：
- `glob "*.db::*.fk"` — 外键关系（精确的 JOIN 条件）
- `glob "*.db::*.rel"` — 语义关系（AI 推断，辅助参考）
- `glob "*.db::*.overlap"` — 列值重叠
- `glob "*.db::*.disambig"` — 语义消歧（同名/近名但含义不同的列或表）

FK 实体名编码了精确的 JOIN 条件，例如 `orders.user_id__to__users.id.fk` 表示 `orders.user_id = users.id`。
rel 实体是 AI 推断的辅助线索，可靠性低于 FK，使用前应验证数据（如 query 抽样确认值匹配）。如果 FK 和 REL 指向同一对表，优先使用 FK。
overlap 实体仅表示列值有重叠，不能直接作为 JOIN 条件使用。

如果两个表之间没有直接关系，可以用 `find_path` 查找通过中间实体的桥接路径，可以发现任何连接关系包括fk，rel，overlap等。

### 输出前检查

再基本完成上述目标之后，你可以尝试写出SQL，但是输出最终结果前必须完成验证以下内容：
1. 确保你读取了输出sql中涉及到的任何实体（表，列，外键，关系等）的基本元数据（包括detail总结，统计信息等）
2. 模糊性的排除，如果SQL中提到的无论是表还是列，有与其字段名等相似的实体，必须明确区分辨析之后再决策。如果有 .disambig 消歧实体，必须读取确认语义。
3. 如果你发现确保join关系的正确性、连贯性、合理性、可解释性。
4，你生成的SQL能在以上信息的约束下形成一个连贯的整体，满足用户提问。

### 写 SQL 前的规划步骤（必须执行）

在开始写 SQL 之前，你必须先在心中（不需要输出）明确以下三点：

1. **需要哪些表**：根据问题和 evidence 确定，不要多加也不要少加
2. **表之间如何 JOIN**：基于 .fk/.rel 确认 JOIN 条件，如果两个表之间没有直接关系，需要找到桥接路径
3. **WHERE 条件是什么**：只包含问题明确要求的过滤条件

**常见错误**：
- 看到外键就把所有关联表都 JOIN 进来 → 只 JOIN 问题实际需要的表
- 问题没有要求排序就加 ORDER BY → 不要加
- 问题没有要求 DISTINCT 就加 DISTINCT → 不要加
- 问题没有要求过滤空值就加 IS NOT NULL → 不要加

### 严格遵循 evidence

如果问题附带了 evidence（证据提示），evidence 中的信息具有高优先级：
- evidence 给出的列名映射 → 优先使用
- evidence 给出的计算公式 → **严格翻译为 SQL**，不要简化或改写
- evidence 给出的条件值 → 直接使用，不要猜测其他值

### 关于 query 工具
query 是辅助验证工具，不是探索工具。探索数据库结构应使用 glob 和 meta。
query 用于验证和确认，帮助确定返回 SQL 的有效性。不要用它反复试错。
过度专注在 query 工具的 SQL 生成上会让你损失全局的语义理解，这是非常危险的！

### 标准执行流程
1. **glob** — 发现文件、表、列、关系等结构
2. **meta** — 读取实体的 detail 字段理解语义（这是最核心的步骤）
3. **确认关系** — 读取 .fk/.rel/.overlap 实体确认 JOIN 路径
4. **检查消歧** — 读取 .disambig 实体排除语义歧义（见下方消歧说明）
5. **query** — 仅在前四步完成后，用于辅助验证或探查

### 消歧实体的特殊重要性
.disambig 实体标记了名称相近但含义不同的表或列。例如：
- `results.position` 是单场比赛完赛名次，`driverStandings.position` 是赛季累计排名
- `results.points` 是单场得分，`driverStandings.points` 是赛季总积分

**忽略消歧实体是错选表/列的首要原因**。输出 SQL 前必须确认已读取并理解所有相关消歧实体。

### 常见错误清单

| 错误模式 | 正确做法 |
|---|---|
| 猜测 JOIN 条件 | 先 glob .fk/.rel 确认 |
| 猜测列名 | 先 meta 确认列语义 |
| 多加/少加列 | 只 SELECT 问题要求的字段 |
| 猜测 WHERE 值 | 先 query SELECT DISTINCT 确认实际值 |
| 用 query 反复试错 | 前三步做完后一次写对 |
| 自作主张加过滤条件 | 只加问题明确要求的 WHERE 条件 |
| 不遵循 evidence 公式 | 严格按 evidence 给出的公式翻译 SQL |
| 代码列和名称列混淆 | meta 查看 topk 和 detail 区分 |
"""


def get_sql_rules() -> str:
    return _SQL_RULES
