_STATIC_PROMPT = r"""## 概念总览

Pontis 为项目中的数据文件提取**逻辑实体**，形成知识图谱。`.pontis/` 目录存储系统数据，不要手动访问。

项目中的每个数据文件都会被解析出一系列逻辑和语义实体，每个实体必然至少与一个物理文件相关。
文件、实体之间通过无向边连接。所有工具通过统一的 **ref** 字符串寻址。

**不要假设项目中有哪些类型的文件** — 先用 `glob "*"` 发现实际存在的文件，再根据返回结果决定下一步。

### Ref 机制

```
<文件路径>                → 文件节点    data.csv
<文件路径>::<实体名>      → 实体节点    data.db::users.table
```

文件节点就是文件在项目中的相对路径。`::` 后面的部分是实体名，由实体类型决定命名规则（详见各文件类型说明）。

---

## 实体归属与图谱结构

glob 工具分两个阶段工作：

1. **文件发现**（`::` 第一段）：扫描文件系统，匹配物理文件
2. **边遍历**（`::` 后续段）：从找到的节点沿边遍历，匹配实体

因此 `::` 第一段必须是文件级 pattern，不能用实体后缀开头。

```
glob "*"                                 → 发现所有文件
glob "某个文件::*"                        → 该文件下的直接实体
glob "某个文件::*.table::*.*.*.col"       → 多跳：表 → 列
glob "某个文件::*.col::*.rel"             → 列 → rel 关系
```

边的类型取决于文件类型和实体类型，详见各文件类型的说明。
边是无向的，可以反向遍历。

---

## 元数据

每个文件节点和逻辑实体都有元数据（meta）。用 `meta` 工具查看。所有实体共享以下通用字段：

| 字段 | 说明 |
|---|---|
| `brief` | AI 生成的简要概括（≤50字） |
| `detail` | AI 生成的详细描述 |

其他字段因实体类型而异，详见各文件类型的说明。

⚠️ **AI 生成内容不可盲信** — brief、detail 以及所有 AI 生成的摘要都只是辅助信息，可能存在错误或偏差。实体名中的结构信息（列名、表名、数据类型）来自数据库元数据，是准确的；但语义描述仅供参考。遇到不确定的情况，应通过 sample、topk 等原始数据验证。

---

## 工具使用策略

1. **先 glob 后 meta 再 read** — 首先探索文件目录结构，然后探索每个文件相关的语义实体信息，从宏观到微观，不要一上来就 read 大文件。
2. **meta 优先** — 大部分信息通过 meta 的 detail 等字段就能回答，不需要读原始数据
3. **利用上下文** — 如果之前的工具调用已经返回了相关数据，直接引用，不要重新调用
"""


